%% ============================================================
% Local function: optimal truth/detection assignment
% =============================================================

function [matchedXY, matchedAlpha, bestAssignment] = ...
    matchDetectionsToTruth( ...
        truthXY, ...
        detectedXY, ...
        detectedAlpha)

numTargets = ...
    size(truthXY,1);


allAssignments = ...
    perms(1:numTargets);


bestCost = ...
    Inf;

bestAssignment = ...
    1:numTargets;


for k = 1:size(allAssignments,1)

    assignment = ...
        allAssignments(k,:);


    candidateXY = ...
        detectedXY(assignment,:);


    errorM = ...
        vecnorm( ...
            candidateXY - ...
            truthXY, ...
            2, ...
            2);


    cost = ...
        sum(errorM);


    if cost < bestCost

        bestCost = ...
            cost;

        bestAssignment = ...
            assignment;

    end

end


matchedXY = ...
    detectedXY(bestAssignment,:);

matchedAlpha = ...
    detectedAlpha(bestAssignment);

end