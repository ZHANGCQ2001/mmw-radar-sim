    10*log10(P + eps));

axis xy equal tight;

clim([-40 0]);

colormap turbo;

colorbar;

xlabel('x / m');
ylabel('y / m');

title('Original four-target multi-carrier image');


hold on;


plot( ...
    truthXY(:,1), ...
    truthXY(:,2), ...
    'wo', ...
    'MarkerSize', ...
    8, ...
    'LineWidth', ...
    1.5);


plot( ...
    detectedXY(:,1), ...
    detectedXY(:,2), ...
    'wx', ...
    'MarkerSize', ...
    8, ...
