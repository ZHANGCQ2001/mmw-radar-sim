function fig = plotOmpSupport(scene, ompResult)
%PLOTOMPSUPPORT Plot truth and recovered OMP supports.

truthPositionM = ...
    vertcat(scene.targets.positionM);


fig = ...
    figure( ...
        'Name', ...
        'OMP recovered targets', ...
        'Color', ...
        'w');


plot( ...
    truthPositionM(:,1), ...
    truthPositionM(:,2), ...
    'ko', ...
    'MarkerSize', ...
    7, ...
    'LineWidth', ...
    1.5);


hold on;


plot( ...
    ompResult.positionsM(:,1), ...
    ompResult.positionsM(:,2), ...
    'rx', ...
    'MarkerSize', ...
    8, ...
    'LineWidth', ...
    1.5);


axis equal;

xlabel('x / m');
ylabel('y / m');

title('OMP recovered targets');

grid on;


legend( ...
    {'Truth', 'OMP estimate'}, ...
    'Location', ...
    'best');


hold off;

end